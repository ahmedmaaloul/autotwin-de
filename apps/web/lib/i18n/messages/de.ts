/**
 * Widen the literal string types produced by `as const` back to `string`, while keeping the
 * key structure exact. That is the whole trick behind the typed catalogue: `en.ts` is declared
 * as `Messages`, so it must supply *every* key the German catalogue has — a forgotten
 * translation is a compile error — but it is free to supply different text.
 */
type Translated<T> = {
  [K in keyof T]: T[K] extends string ? string : Translated<T[K]>;
};

