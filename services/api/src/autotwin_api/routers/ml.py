"""``/api/v1/ml`` — the model registry, its evidence, and predictions with their attribution.

Two stores describe the same models and both are read here. The **models directory** is the
serving truth: the artefact and its ``*.metrics.json`` sidecar are what can actually answer a
request. The **``ml_models`` table** is the queryable truth, and is what carries the row id the
frontend selects on. ``GET /ml/models`` prefers the table and falls back to the directory with a
deterministic id, so a freshly cloned repository — artefacts committed, database empty — still
lists its models instead of claiming none exist.

Metrics are **read**, never recomputed. The numbers in the sidecar are the ones the model was
evaluated with, on the split it was evaluated on; an endpoint that re-scored on request would
quietly report a different test set every time the training data changed.

Nothing trained yet answers **503 `configuration_missing`** — the same code the copilot uses for
"this deployment is not configured for that". The registry raises the condition as
``ModelNotAvailable`` (503 ``model_not_available``); it is remapped here so a client has one
code to switch on for the whole family, and the message always names the command that fixes it.
"""

